r"""
第 6.5 单元 · 第 1 课 练习：用 SQL 从表里取数据
------------------------------------------------------------------
运行：  D:\python\python.exe sql_practice_1.py
规则：  ★ 只填 TODO 引号里的 SQL，下面的管道代码不要动 ★

今天的 4 个关键词（记住顺序就是它们的书写顺序）：
    SELECT   要哪些列          （对应 Pandas 挑列）
    FROM     从哪张表拿        （对应 df）
    WHERE    只要满足条件的行  （对应 布尔索引）
    ORDER BY 按什么排序        （对应 sort_values）
    LIMIT    最多要几行        （对应 head）
"""
import os
import sqlite3

BASE = os.path.dirname(os.path.abspath(__file__))
conn = sqlite3.connect(os.path.join(BASE, "销售.db"))
cursor = conn.cursor()


def show(sql, title):
    """万能骨架：跑一条 SQL，把结果打印成表格（不用改）"""
    print("=" * 60)
    print(title)
    print("SQL >", " ".join(sql.split()))       # 打印你写的 SQL（压缩空格）
    print("-" * 60)

    # try/except 保护：某一题写错，只报这一题，后面照常跑
    try:
        cursor.execute(sql)                     # 执行 SQL
        rows = cursor.fetchall()                # 取出全部结果
        cols = [c[0] for c in cursor.description]   # 取列名
        print(" | ".join(cols))                 # 表头
        for r in rows:
            print(" | ".join(str(x) for x in r))    # 每一行
        print(f"（{len(rows)} 行）\n")
    except sqlite3.Error as e:
        print("❌ SQL 报错：", e)
        print("   检查：关键字拼写 / 有没有 FROM / 引号是否闭合 / 字段名对不对\n")


# ─────────────────────────────────────────────────────────────
# 题 1【看全貌】把【订单】表的所有列都取出来，但只要前 5 行。
#    Pandas 对照： df.head()
#    提示：所有列 = 星号 *
# ─────────────────────────────────────────────────────────────
show("""
select * from 订单 limit 5
""", "题 1：查看订单前 5 行")

# ─────────────────────────────────────────────────────────────
# 题 2【只要两列】只取 商品名称 和 销售额 这两列，全部 40 行。
#    Pandas 对照： df[["商品名称", "销售额"]]
#    提示：多个列名之间用英文逗号隔开，不要加 LIMIT
# ─────────────────────────────────────────────────────────────
show("""
select 商品名称,销售额 from 订单
""", "题 2：只要商品名称和销售额")

# ─────────────────────────────────────────────────────────────
# 题 3【筛选一行条件】找出所有【深圳】的订单，显示全部列。
#    Pandas 对照： df[df["城市"] == "深圳"]
#    ⚠️⚠️ SQL 里"等于"就是【一个】= ，不是 Python 的 == ！
#    ⚠️⚠️ 文字要用【单引号】包起来： '深圳'
# ─────────────────────────────────────────────────────────────
show("""
select * from 订单 where 城市 = '深圳'
""", "题 3：深圳的订单")

# ─────────────────────────────────────────────────────────────
# 题 4【两个条件】找出【数量 >= 5】并且【类别是 饮料】的订单，全部列。
#    Pandas 对照： df[(df["数量"] >= 5) & (df["类别"] == "饮料")]
#    提示：SQL 用 AND 连接两个条件（比 Pandas 的 & 好写多了）
# ─────────────────────────────────────────────────────────────
show("""
select * from 订单 where 数量>=5 and 类别='饮料'
""", "题 4：数量>=5 且是饮料")

# ─────────────────────────────────────────────────────────────
# 题 5【排序 + 限量】找出销售额最高的 3 笔订单，显示全部列。
#    Pandas 对照： df.sort_values("销售额", ascending=False).head(3)
#    提示：从高到低 = DESC（从低到高是 ASC，默认就是 ASC 不用写）
#    ⚠️ ORDER BY 要写在 WHERE 后面、LIMIT 前面，顺序不能乱！
# ─────────────────────────────────────────────────────────────
show("""
select * from 订单 order by 销售额 DESC limit 3
""", "题 5：销售额最高的 3 笔")

# ─────────────────────────────────────────────────────────────
# 题 6【挑战题】只取 订单编号 / 城市 / 销售额 三列，
#    条件是 城市是【上海】或【广州】，按销售额【从低到高】排序。
#    Pandas 对照： df[df["城市"].isin(["上海","广州"])].sort_values("销售额")
#    提示：或者 = OR ；挑列和 WHERE 可以同时用
# ─────────────────────────────────────────────────────────────
show(
"""select 订单编号,城市,销售额 from 订单 where 城市='上海' or 城市='广州' order by 销售额""",
 "题 6：挑战——上海或广州的订单")

conn.close()
print("全部跑完！如果有题报错，把报错贴给我。")
