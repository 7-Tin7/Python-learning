# -*- coding: utf-8 -*-
r"""
第 6.5 单元 · 第 2 课 练习：聚合与分组（GROUP BY）
==================================================================
运行：  D:\python\python.exe sql_practice_2.py
规则：  ★ SQL 写在【三引号里面】★
        ★ 标点必须是半角（，！会把 SQL 弄崩）★
        ★ 表名/列名逐字对齐：表叫【订单】，不叫"订单表" ★

━━━ 本课新东西（就这 5 样，别怕）━━━
  ① 聚合函数：COUNT(*) / SUM(列) / AVG(列) / MAX(列) / MIN(列)
     —— 把"一堆行"压成"一个数"
  ② GROUP BY 列名   —— 把行【分堆】，每堆算一次聚合
  ③ AS 别名         —— 给算出来的列起个名字，好看又好用
  ④ HAVING 条件     —— 筛【堆】（WHERE 筛的是【行】）⭐ 面试高频
  ⑤ 整数除法陷阱     —— 占比算出来是 0 的元凶（题 8 会撞上）

━━━ 上一课 vs 这一课 ━━━
  第 1 课：WHERE  → 挑出【行】（明细，一行一行看）
  第 2 课：GROUP BY → 把行【分堆】，每堆压成一个数（汇总）
  比喻：一堆混着的衣服 → 按类别分堆 → 每堆数件数、称总重

━━━ Pandas 对照（你已经会右边）━━━
  df.groupby("类别")["销售额"].sum()          ↔  SELECT 类别, SUM(销售额) FROM 订单 GROUP BY 类别
  df.groupby("类别")["销售额"].agg(["count","sum"])  ↔  SELECT 类别, COUNT(*), SUM(销售额) ... GROUP BY 类别
  df["销售额"].sum()                          ↔  SELECT SUM(销售额) FROM 订单
  df["销售额"].mean()                         ↔  SELECT AVG(销售额) FROM 订单

表【订单】的列（9 列）：
    订单编号  日期  商品名称  类别  单价  数量  城市  月份  销售额
"""
import os
import sqlite3

BASE = os.path.dirname(os.path.abspath(__file__))
conn = sqlite3.connect(os.path.join(BASE, "销售.db"))
cursor = conn.cursor()


def show(sql, title):
    """万能骨架：跑一条 SQL，把结果打印成表格（不用改）"""
    print("=" * 66)
    print(title)
    print("SQL >", " ".join(sql.split()))
    print("-" * 66)
    try:
        cursor.execute(sql)
        rows = cursor.fetchall()
        cols = [c[0] for c in cursor.description]
        print(" | ".join(cols))
        for r in rows:
            print(" | ".join(str(x) for x in r))
        print(f"（{len(rows)} 行）\n")
    except sqlite3.Error as e:
        print("❌ SQL 报错：", e)
        print("   检查：表名逐字对齐 / 标点半角 / 有没有 GROUP BY / 列名对不对\n")


print("【表 订单 的结构】")
cursor.execute("PRAGMA table_info(订单)")
for c in cursor.fetchall():
    print(f"    {c[1]:<8}  {c[2]}")
print()


# ─────────────────────────────────────────────────────────────
# 题 1【整表汇总 —— 不用 GROUP BY】
#    运营问："这批订单一共多少笔？总卖了多少钱？平均每单多少钱？"
#    要求三列：订单数（COUNT）、总销售额（SUM）、平均客单价（AVG，四舍五入 2 位）
#    考点：COUNT(*) / SUM / AVG + ROUND(值, 位数)
#
#    ✅ 对账目标（你第 6 周报告里的数字）：
#       订单数 40 | 总销售额 8148.60 | 平均客单价 203.72
#       跑出来数字一样 → 说明你写对了！
# ─────────────────────────────────────────────────────────────
show("""
select count(*) as 订单数,sum(销售额) as 总销售额,round(avg(销售额),2) as 平均客单价 from 订单
""", "题 1：整表汇总（对账 40 / 8148.6 / 203.72）")


# ─────────────────────────────────────────────────────────────
# 题 2【分组 ⭐ 本课核心】按【类别】汇总销售额，从高到低排。
#    要两列：类别、该类别的销售额合计。
#    Pandas 对照： df.groupby("类别")["销售额"].sum().sort_values(ascending=False)
#    考点：GROUP BY + SUM + ORDER BY
#
#    ✅ 对账目标（第 6 周报告的品类数据）：
#       水果 4502.1 > 饮料 2298.2 > 零食 1206.8 > 蔬菜 141.5
# ─────────────────────────────────────────────────────────────
show("""
select 类别,sum(销售额) as 总销售额 from 订单 group by 类别 order by sum(销售额) DESC
""", "题 2：按类别汇总销售额（对账 4502.1 / 2298.2 / 1206.8 / 141.5）")


# ─────────────────────────────────────────────────────────────
# 题 3【一堆要两个统计】按类别给出：总额、单数，按总额降序。
#    要三列：类别、总额、单数（单数用 COUNT(*)）
#    考点：一个 GROUP BY 里可以配多个聚合函数
#    期望单数：水果 20 / 饮料 9 / 零食 7 / 蔬菜 4
# ─────────────────────────────────────────────────────────────
show("""
select 类别,sum(销售额) as 总额,count(*) as 单数 from 订单 group by 类别 order by sum(销售额) DESC
""", "题 3：按类别的 总额 + 单数")


# ─────────────────────────────────────────────────────────────
# 题 4【分组 + 排序 + 限量】哪个商品最赚钱？
#    按【商品名称】汇总销售额，取前 3 名。
#    要两列：商品名称、销售额合计
#    考点：GROUP BY + ORDER BY + LIMIT 三个一起用（顺序别乱）
# ─────────────────────────────────────────────────────────────
show("""
select 商品名称,round(sum(销售额),2) as 销售额合计 from 订单 group by 商品名称 order by 销售额合计 DESC limit 3
""", "题 4：销售额前 3 的商品")


# ─────────────────────────────────────────────────────────────
# 题 5【分组 + 排序】按【城市】汇总销售额，从高到低。
#    要两列：城市、销售额合计。应该有 6 行（含"未知"）。
#    考点：和题 2 同型，换个列分组
# ─────────────────────────────────────────────────────────────
show("""
select 城市,sum(销售额) as 销售额合计 from 订单 group by 城市 order by 销售额合计 DESC
""", "题 5：按城市汇总销售额")


# ─────────────────────────────────────────────────────────────
# 题 6【HAVING ⭐ 面试高频】只看"销售额合计超过 1000 元"的类别。
#    要两列：类别、销售额合计，按总额降序。
#
#    ⚠️⚠️ 关键：这里不能用 WHERE！
#        WHERE 是筛【行】（明细行），而"合计超过1000"是【分组之后】才知道的。
#        要筛"堆"，必须用 HAVING，且写在 GROUP BY 【后面】。
#
#    考点：HAVING 的位置和用途
# ─────────────────────────────────────────────────────────────
show("""
select 类别,sum(销售额) as 销售额合计 from 订单 group by 类别 having sum(销售额) > 1000 order by 销售额合计 DESC
""", "题 6：总额超过 1000 的类别（必须用 HAVING）")


# ─────────────────────────────────────────────────────────────
# 题 7【WHERE 和 GROUP BY 一起用】先剔除"未知"城市，再按城市汇总，取前 3。
#    要两列：城市、销售额合计
#
#    ⚠️ 顺序：WHERE 在 GROUP BY 【前面】！
#       先筛行（WHERE）→ 再分堆（GROUP BY）→ 再排序（ORDER BY）
#    考点：WHERE 和 GROUP BY 的先后顺序
# ─────────────────────────────────────────────────────────────
show("""
select 城市,sum(销售额) as 销售额合计 from 订单 where 城市 != '未知' group by 城市 order by 销售额合计 DESC limit 3
""", "题 7：剔除未知城市后，销售额前 3 的城市")


# ─────────────────────────────────────────────────────────────
# 题 8【按月汇总 —— 复现你第 6 周的关键发现】
#    按【月份】给出：单数、总额、客单价（AVG，四舍五入 2 位），按月份升序。
#    要四列：月份、单数、总额、客单价
#
#    ✅ 对账目标：你会看到 2 月【单数最多（15）但客单价最低】——
#       这就是你第 6 周报告里"2 月不是淡季，是客单价下降"的证据来源！
#
#    💡 客单价两种写法都对：
#       ① AVG(销售额)             ← 推荐，一行搞定
#       ② SUM(销售额)/COUNT(*)    ← 也对（销售额是小数类型，相除不会丢小数）
#       ⚠️ 但"两个整数相除"要小心：COUNT/COUNT、整数列/整数列，
#          除不尽时会悄悄丢掉小数变成 0（详见笔记第八节坑 1）。
# ─────────────────────────────────────────────────────────────
show("""
select 月份,count(*) as 单数,sum(销售额) as 总额,round(avg(销售额),2) as 客单价 from 订单 group by 月份 order by 月份
""", "题 8：按月份的 单数 / 总额 / 客单价")


# ─────────────────────────────────────────────────────────────
# 题 9【挑战：HAVING 筛数量】只看"订单数在 5 笔以上（含 5 笔）"的城市，
#    列出 城市、单数、总额，按总额降序。
#    考点：HAVING 里不只能筛 SUM，也能筛 COUNT(*)
# ─────────────────────────────────────────────────────────────
show("""
select 城市,count(*) as 单数,sum(销售额) as 总额 from 订单 group by 城市 having count(*) >= 5 order by 总额 DESC
""", "题 9【挑战】：订单数≥5 的城市")


conn.close()
print("全部跑完！把结果贴给我。题 1、2、8 请重点对照你第 6 周报告的数字。")
