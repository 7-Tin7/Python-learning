import os
import sqlite3

BASE = os.path.dirname(os.path.abspath(__file__))
conn = sqlite3.connect(os.path.join(BASE, "销售.db"))
cursor = conn.cursor()


def show(sql, title, commit=False):
    """万能骨架：跑一条 SQL，把结果打印成表格（不用改）"""
    print("=" * 68)
    print(title)
    print("SQL >", " ".join(sql.split()))
    print("-" * 68)
    try:
        cursor.execute(sql)
        if commit:                      # 改动数据的语句要 commit
            conn.commit()
            print("✅ 已提交（commit）")
        rows = cursor.fetchall()
        if cursor.description:          # SELECT 才有列名
            cols = [c[0] for c in cursor.description]
            print(" | ".join(cols))
            for r in rows:
                print(" | ".join(str(x) for x in r))
            print(f"（{len(rows)} 行）")
        else:
            print(f"✅ 影响 {cursor.rowcount} 行")
    except sqlite3.Error as e:
        print("❌ SQL 报错：", e)
        print("   检查：表名逐字对齐 / 有没有写 ON / 列名对不对 / 标点半角")
    print()


print("【表 订单】")
cursor.execute("PRAGMA table_info(订单)")
print("   ", " / ".join(c[1] for c in cursor.fetchall()))
print("【表 商品成本】")
cursor.execute("PRAGMA table_info(商品成本)")
