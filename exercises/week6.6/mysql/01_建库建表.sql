-- ════════════════════════════════════════════════════════════════════════
-- 【本课的核心知识点：SQLite 的类型 vs MySQL 的类型】
--
-- 你在第 6.5 单元建的库，列类型是这么来的（Python 里建表时写的）：
--     订单编号 TEXT / 日期 TEXT / 商品名称 TEXT / 类别 TEXT
--     单价 REAL / 数量 INTEGER / 城市 TEXT / 月份 INTEGER / 销售额 REAL
--
-- ⚠️ SQLite 是"动态类型"：类型只是个建议，存字符串进去也不报错。
--    MySQL 是"严格类型"：说好是 INT，你塞个 'abc' 就报错。
--    所以 MySQL 里要指定【长度】和【精度】：
--
--   SQLite 写的  →  MySQL 该写什么            说明
--   ────────────────────────────────────────────────────────────────
--   TEXT         →  VARCHAR(20)               短文本要写最大长度
--                   TEXT                      长文本才用 TEXT
--   INTEGER      →  INT                       基本一样
--   REAL         →  DECIMAL(10,2)             ⚠️ 钱必须用 DECIMAL！
--                   （或 FLOAT/DOUBLE）          用 FLOAT 算钱会有精度误差
--   '2026-01-01' →  DATE                       日期有专门的类型
--
-- ⚠️⚠️ 为什么钱要用 DECIMAL 而不是 FLOAT？这题面试爱问：
--    浮点数（FLOAT/DOUBLE）存 0.1 这种数是【近似值】，
--    多个数加起来可能得到 0.30000000000000004。
--    DECIMAL 是精确定点数，专门用来存钱。
--    （SQLite 里你用的是 REAL，也就是浮点——这是 SQLite 的简化）
--
-- 【反引号 ` 是干什么的】
--    MySQL 用反引号包住"标识符"（库名/表名/列名），
--    中文表名建议一律加上，最保险，能避开很多解析问题：
--        SELECT * FROM `订单` WHERE `类别` = '水果';
--    ⚠️ 别和字符串的单引号 ' 搞混：
--        反引号 ` ` → 包【名字】
--        单引号 ' ' → 包【值】
-- ════════════════════════════════════════════════════════════════════════


